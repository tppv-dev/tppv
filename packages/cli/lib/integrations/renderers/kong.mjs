function smokeTest(spec) {
  return `#!/usr/bin/env bash
# Smoke test for the generated ${PLUGIN_NAME} plugin.
#
# Expectations:
#   1. no client certificate           -> ${spec.denyStatus} NoClientCertificate
#   2. self-signed non-PSD2 cert       -> ${spec.denyStatus} (first failing check)
#   3. real QWAC                       -> 200, upstream sees x-tpp-* headers
#
# Case 3 needs a certificate that actually validates. Point QWAC at one, or
# leave it unset and case 3 is reported as skipped rather than silently passing.

set -euo pipefail

BASE=\${BASE:-https://localhost:8443}
ROUTE=\${ROUTE:-/v1/accounts}
QWAC=\${QWAC:-}
QWAC_KEY=\${QWAC_KEY:-}

pass() { printf '  \\033[32mok\\033[0m   %s\\n' "$1"; }
fail() { printf '  \\033[31mfail\\033[0m %s\\n' "$1"; exit 1; }
skip() { printf '  \\033[2mskip\\033[0m %s\\n' "$1"; }

echo "1. no client certificate"
code=$(curl -sk -o /dev/null -w '%{http_code}' "$BASE$ROUTE")
[ "$code" = "${spec.denyStatus}" ] && pass "denied with $code" || fail "expected ${spec.denyStatus}, got $code"

echo "2. self-signed certificate"
tmp=$(mktemp -d)
openssl req -x509 -newkey rsa:2048 -nodes -days 1 -subj '/CN=not-a-tpp.example' \\
  -keyout "$tmp/k.pem" -out "$tmp/c.pem" 2>/dev/null
code=$(curl -sk -o /dev/null -w '%{http_code}' --cert "$tmp/c.pem" --key "$tmp/k.pem" "$BASE$ROUTE")
reason=$(curl -sk -D - -o /dev/null --cert "$tmp/c.pem" --key "$tmp/k.pem" "$BASE$ROUTE" \\
  | tr -d '\\r' | awk -F': ' '/^x-tpp-reason/ {print $2}')
rm -rf "$tmp"
[ "$code" = "${spec.denyStatus}" ] && pass "denied with $code (x-tpp-reason: \${reason:-none})" \\
  || fail "expected ${spec.denyStatus}, got $code"

echo "3. valid QWAC"
if [ -z "$QWAC" ] || [ -z "$QWAC_KEY" ]; then
  skip "set QWAC and QWAC_KEY to exercise the allow path"
  exit 0
fi
body=$(curl -sk --cert "$QWAC" --key "$QWAC_KEY" "$BASE$ROUTE/headers")
echo "$body" | grep -qi 'x-tpp-identifier' \\
  && pass "allowed, upstream received x-tpp-* headers" \\
  || fail "allowed but header injection missing: $body"
`;
}

