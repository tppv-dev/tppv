/**
 * Kong Gateway renderer — custom Lua plugin.
 *
 * The verdict logic is not written by hand here: CHECKS is serialized straight
 * out of VERDICT_RULE, so the Lua and the CLI can never drift.
 *
 * No timestamps or random identifiers are emitted anywhere, so regenerating
 * with the same answers produces byte-identical output and a clean git diff.
 */

import { describeSpec } from '../contract.mjs';

const PLUGIN_NAME = 'tpp-validation';
const PLUGIN_VERSION = '1.0.0';

function luaStr(s) {
  return `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function luaPath(path) {
  return `{ ${path.map(luaStr).join(', ')} }`;
}

function luaChecks(rule) {
  return rule
    .map((r) => {
      const parts = [
        `id = ${luaStr(r.id)}`,
        `path = ${luaPath(r.path)}`,
        `op = ${luaStr(r.op)}`,
      ];
      if (r.value !== undefined) parts.push(`value = ${luaStr(r.value)}`);
      parts.push(`reason = ${luaStr(r.reason)}`);
      return `  { ${parts.join(', ')} },`;
    })
    .join('\n');
}

function luaInjectList(headers) {
  return headers.map((h) => `  ${luaStr(h.header)},`).join('\n');
}

function luaInjectMap(headers) {
  return headers
    .map((h) => {
      const read = h.fallbackPath
        ? `dig(data, ${luaPath(h.path)}) or dig(data, ${luaPath(h.fallbackPath)})`
        : `dig(data, ${luaPath(h.path)})`;
      return `      [${luaStr(h.header)}] = ${read},`;
    })
    .join('\n');
}

function luaRoleList(roles) {
  return roles.length ? `{ ${roles.map(luaStr).join(', ')} }` : '{}';
}

function specHeader(spec, comment = '--') {
  const lines = describeSpec(spec).map(([k, v]) => `${comment} ${k.padEnd(20)} ${v}`);
  return [
    `${comment} Generated by tppv integration — do not edit by hand.`,
    `${comment} Regenerate: tppv integration --gateway ${spec.target.id}`,
    comment,
    ...lines,
  ].join('\n');
}

function handlerLua(spec) {
  return `${specHeader(spec)}

local cjson = require "cjson.safe"
local http = require "resty.http"
local sha256 = require "resty.sha256"
local resty_string = require "resty.string"

local kong = kong
local ngx = ngx
local NULL = cjson.null

local PLUGIN_NAME = ${luaStr(PLUGIN_NAME)}
local PLUGIN_VERSION = ${luaStr(PLUGIN_VERSION)}
local RULE_VERSION = ${spec.ruleVersion}

local TppValidation = {
  -- After mtls-auth (1006), so the client certificate is already negotiated.
  -- Before rate-limiting (901) and request-transformer, so traffic that will be
  -- rejected never consumes quota and never reaches a transform.
  PRIORITY = 1005,
  VERSION = PLUGIN_VERSION,
}

-- Serialized from VERDICT_RULE in lib/verdict.mjs. Do not hand-edit: the CLI
-- verdict and this table must stay identical or the gateway and the dashboard
-- will disagree about the same certificate.
local CHECKS = {
${luaChecks(spec.rule)}
}

local OK_FLAGS = { [true] = true, PASSED = true, GOOD = true, granted = true, yes = true, [1] = true }

-- Cleared from every inbound request before we set them. A caller able to send
-- x-tpp-identifier could otherwise impersonate a different TPP to the upstream.
local INJECT_HEADERS = {
${luaInjectList(spec.injectedHeaders)}
}

local FINGERPRINT_HEADER = "x-tpp-fingerprint"

---------------------------------------------------------------------------
-- verdict evaluation
---------------------------------------------------------------------------

local function dig(node, path)
  local cur = node
  for i = 1, #path do
    if type(cur) ~= "table" then return nil end
    cur = cur[path[i]]
    if cur == nil or cur == NULL then return nil end
  end
  return cur
end

-- Days since the Unix epoch, UTC. os.time() would interpret the fields as
-- local time and shift expiry by the container's offset.
local function days_from_civil(y, m, d)
  if m <= 2 then y = y - 1 end
  local era = math.floor(y / 400)
  local yoe = y - era * 400
  local mp = m + (m > 2 and -3 or 9)
  local doy = math.floor((153 * mp + 2) / 5) + d - 1
  local doe = yoe * 365 + math.floor(yoe / 4) - math.floor(yoe / 100) + doy
  return era * 146097 + doe - 719468
end

local function iso_to_epoch(s)
  if type(s) ~= "string" then return nil end
  local y, mo, d, h, mi, sec = string.match(s, "^(%d%d%d%d)-(%d%d)-(%d%d)[T ](%d%d):(%d%d):(%d%d)")
  if not y then
    y, mo, d = string.match(s, "^(%d%d%d%d)-(%d%d)-(%d%d)")
    h, mi, sec = "0", "0", "0"
  end
  if not y then return nil end
  return days_from_civil(tonumber(y), tonumber(mo), tonumber(d)) * 86400
    + tonumber(h) * 3600 + tonumber(mi) * 60 + tonumber(sec)
end

local function test_op(chk, value)
  local op = chk.op

  if op == "okFlag" then
    return OK_FLAGS[value] == true

  elseif op == "equals" then
    return value == chk.value

  elseif op == "truthy" then
    return value ~= nil and value ~= false

  elseif op == "nonEmpty" then
    return type(value) == "string" and #value > 0

  elseif op == "future" then
    if value == nil then return false end
    local epoch = iso_to_epoch(value)
    -- An unparseable notAfter is not treated as expired. /v5 already reports
    -- expiry as certificateRevocation = "EXPIRED", which the revocation check
    -- catches, so denying here as well would turn a date-format change on the
    -- API side into a full outage.
    if not epoch then
      kong.log.warn("unparseable notAfter, expiry check skipped: ", tostring(value))
      return true
    end
    return epoch > ngx.time()

  elseif op == "nonEmptyFirstEntry" then
    return type(value) == "table" and type(value[1]) == "table" and next(value[1]) ~= nil
  end

  kong.log.err("unknown verdict op: ", tostring(op))
  return false
end

local function evaluate(data)
  if type(data) ~= "table" then
    return false, "NoValidationResponse", "response"
  end
  for i = 1, #CHECKS do
    local chk = CHECKS[i]
    if not test_op(chk, dig(data, chk.path)) then
      return false, chk.reason, chk.id
    end
  end
  return true
end

---------------------------------------------------------------------------
-- validator call
---------------------------------------------------------------------------

local function fingerprint(pem)
  local digest = sha256:new()
  digest:update(pem)
  return resty_string.to_hex(digest:final())
end

local function call_validator(conf, pem)
  local httpc = http.new()
  httpc:set_timeout(conf.timeout_ms)

  local url = conf.api_url .. "?cc=" .. ngx.escape_uri(conf.jurisdictions) .. "&details=true"
  local res, err = httpc:request_uri(url, {
    method = "POST",
    body = pem,
    headers = {
      ["Content-Type"] = "text/plain",
      ["Authorization"] = "Bearer " .. conf.bearer_token,
      ["User-Agent"] = "tpp-validation-kong/" .. PLUGIN_VERSION,
    },
    ssl_verify = true,
    keepalive_timeout = 60000,
    keepalive_pool = 8,
  })

  if not res then
    return nil, "validator unreachable: " .. tostring(err)
  end
  if res.status == 401 then
    return nil, "validator rejected the bearer token (401) — check the vault reference"
  end
  -- 200 = validated, 422 = validated and failed. Both carry a usable body;
  -- anything else is an infrastructure problem, not a verdict.
  if res.status ~= 200 and res.status ~= 422 then
    return nil, "validator returned HTTP " .. tostring(res.status)
  end

  local data = cjson.decode(res.body)
  if not data then
    return nil, "validator returned unparseable JSON"
  end
  return data
end

-- mlcache callback. The third return value overrides the entry TTL, which is
-- how deny verdicts get a shorter life than allow verdicts.
local function load_verdict(conf, pem)
  local data, err = call_validator(conf, pem)
  if not data then
    return nil, err
  end

  local allowed, reason, failed_id = evaluate(data)
  local entry = {
    allowed = allowed,
    reason = reason,
    failed = failed_id,
    inject = {
${luaInjectMap(spec.injectedHeaders)}
    },
  }

  local ttl = allowed and conf.cache_ttl_seconds or conf.negative_cache_ttl_seconds
  return entry, nil, ttl
end

---------------------------------------------------------------------------
-- decision
---------------------------------------------------------------------------

local function deny(conf, status, reason, detail)
  -- detail goes to the log, never to the caller: a TPP does not need to know
  -- which internal check tripped or whether our validator was reachable.
  kong.log.warn(PLUGIN_NAME, " denied: ", reason, " — ", tostring(detail))
  return kong.response.exit(status, {
    error = "tpp_validation_failed",
    reason = reason,
  }, {
    ["x-tpp-reason"] = reason,
  })
end

local function role_permitted(allowed, role)
  for candidate in string.gmatch(tostring(role), "[^,%s]+") do
    for i = 1, #allowed do
      if allowed[i] == candidate then return true end
    end
  end
  return false
end

function TppValidation:access(conf)
  for i = 1, #INJECT_HEADERS do
    kong.service.request.clear_header(INJECT_HEADERS[i])
  end
  kong.service.request.clear_header(FINGERPRINT_HEADER)

  local pem, cert_err = kong.client.tls.get_full_client_certificate_chain()
  if not pem then
    return deny(conf, conf.deny_status, "NoClientCertificate",
      "no client certificate on the connection" .. (cert_err and (": " .. cert_err) or "") ..
      " — check nginx_proxy_ssl_verify_client")
  end

  local fp = fingerprint(pem)
  local cache_key = "tppv:r" .. RULE_VERSION .. ":" .. fp .. ":" .. conf.jurisdictions

  local entry, err, hit_level

  if conf.cache_ttl_seconds <= 0 then
    -- mlcache reads ttl = 0 as "never expires", the opposite of caching off,
    -- so bypass the cache entirely rather than passing 0 through.
    entry, err = load_verdict(conf, pem)
  else
    local opts = {
      ttl = conf.cache_ttl_seconds,
      neg_ttl = conf.negative_cache_ttl_seconds,
    }
    if conf.fail_mode == "closed_grace" and conf.grace_ttl_seconds > 0 then
      -- resurrect_ttl serves the stale verdict when the callback errors. This
      -- is the grace window — no bespoke bookkeeping needed.
      opts.resurrect_ttl = conf.grace_ttl_seconds
    end
    entry, err, hit_level = kong.cache:get(cache_key, opts, load_verdict, conf, pem)
  end

  if not entry then
    kong.log.err("validator unavailable: ", tostring(err))
    if conf.fail_mode == "open" then
      kong.log.warn("fail_mode=open — admitting unvalidated certificate ", fp)
      kong.service.request.set_header("x-tpp-validation", "bypassed")
      return
    end
    return deny(conf, conf.unavailable_status, "ValidatorUnavailable", err)
  end

  if err then
    -- Value came back with an error attached: mlcache resurrected a stale
    -- verdict, so we are inside the grace window. Worth an alert, not a deny.
    kong.log.warn("grace window: reusing cached verdict for ", fp,
      " (mlcache hit level ", tostring(hit_level), ") during outage: ", tostring(err))
  end

  if not entry.allowed then
    return deny(conf, conf.deny_status, entry.reason or "ValidationFailed",
      "failed check: " .. tostring(entry.failed))
  end

  if #conf.allowed_roles > 0 then
    local role = entry.inject and entry.inject["x-tpp-roles"]
    if not role or not role_permitted(conf.allowed_roles, role) then
      return deny(conf, conf.deny_status, "RoleNotPermitted",
        "role " .. tostring(role) .. " not permitted on this route")
    end
  end

  if conf.inject_headers then
    for i = 1, #INJECT_HEADERS do
      local header = INJECT_HEADERS[i]
      local value = entry.inject and entry.inject[header]
      if value ~= nil then
        kong.service.request.set_header(header, tostring(value))
      end
    end
    kong.service.request.set_header(FINGERPRINT_HEADER, fp)
  end
end

return TppValidation
`;
}

